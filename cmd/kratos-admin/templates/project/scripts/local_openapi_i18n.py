def split_english_run(value: str) -> str:
    """拆分本地术语替换后粘连的英文单词。"""
    lower = value.lower()
    size = len(lower)
    paths: list[list[str] | None] = [None] * (size + 1)
    paths[0] = []
    for start in range(size):
        if paths[start] is None:
            continue
        for end in range(start + 3, size + 1):
            word = lower[start:end]
            if word not in EN_WORDS:
                continue
            candidate = [*paths[start], word]
            current = paths[end]
            if current is None or len(candidate) < len(current):
                paths[end] = candidate
    if paths[size] is None or len(paths[size]) < 2:
        return value
    return " ".join(paths[size])


def normalize_english_spacing(value: str) -> str:
    """统一英文译文中的大小写边界和连续单词间距。"""
    value = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", value)
    return re.sub(r"[A-Za-z]{4,}", lambda match: split_english_run(match.group(0)), value)

