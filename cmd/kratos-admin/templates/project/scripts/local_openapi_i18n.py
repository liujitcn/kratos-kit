def contains_simplified(value: str) -> bool:
    """判断译文是否仍包含明显的简体中文残留。"""
    return any(marker in value for marker in SIMPLIFIED_MARKERS)


def local_translate(value: str, locale: str) -> str:
    """使用项目内术语表翻译单条 OpenAPI 文案。"""
    exact = EN_EXACT if locale == "en-US" else JA_EXACT
    terms = EN_ORDERED_TERMS if locale == "en-US" else JA_ORDERED_TERMS
    translated = exact.get(value, value)
    if translated != value:
        return translated
    replacements = dict(terms)
    pattern = re.compile("|".join(re.escape(source) for source in replacements))
    translated = pattern.sub(lambda match: replacements[match.group(0)], value)
    if locale == "en-US":
        translated = normalize_english_spacing(translated)
        translated = translated.replace("。", ".").replace("，", ", ").replace("：", ": ")
    else:
        translated = translated.replace("。", "。")
    return translated
